export type RouteProfileId = keyof typeof routeProfiles;
export const routeProfileIds = Object.keys(routeProfiles) as RouteProfileId[];

export function routeKind(
  profile: RouteProfileId,
  floor: number,
  depth: number,
): NodeKind {
  if (floor === depth - 1) return "boss";
  const sequence = routeProfiles[profile].sequence as readonly NodeKind[];
  return sequence[floor % (sequence.length - 1)];
}
