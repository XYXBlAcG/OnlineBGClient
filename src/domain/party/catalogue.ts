export type PartyItemId = keyof typeof partyItems;
export const partyTiers = [
  { earned: 0, discount: 1 },
  { earned: 200, discount: 0.9 },
  { earned: 600, discount: 0.75 },
  { earned: 1500, discount: 0.6 },
  { earned: 4000, discount: 0.45 },
] as const;
export function partyTier(earned: number): number {
  return partyTiers.filter((t) => earned >= t.earned).length - 1;
}
export function discountedPartyPrice(price: number, earned: number): number {
  return Math.max(
    1,
    Math.ceil(price * partyTiers[Math.max(0, partyTier(earned))].discount),
  );
}
export function partyPrice(id: PartyItemId, earned: number): number {
  return discountedPartyPrice(partyItems[id].price, earned);
}
