export class CardGuides {
  private cards;
  constructor(runtime = new UpstreamRuntime()) {
    this.cards = runtime.load(8280);
  }
  get(id: number): CardGuide | null {
    if (!Number.isInteger(id) || id < 0) return null;
    const type = this.cards.e3(id);
    const row = explanations[type];
    if (!row) return null;
    const [timing, target, effect, response, example] = row;
    return {
      type,
      name: cardName(type),
      timing,
      target,
      effect,
      response,
      example,
    };
  }
}
