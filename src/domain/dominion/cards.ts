export interface CardDefinition {
  name: string;
  cost: number;
  type: "treasure" | "victory" | "curse" | "action";
  text: string;
  symbol: string;
  kingdom?: boolean;
  attack?: boolean;
  reaction?: boolean;
  value?: number;
  points?: number;
  cards?: number;
  actions?: number;
  buys?: number;
  coins?: number;
  effect?: string;
}
