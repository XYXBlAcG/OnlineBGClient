export class HeroGuides {
  private runtime = new UpstreamRuntime();
  all(): HeroGuide[] {
    const rows = this.runtime.load(8467).V6 as [
      string,
      number,
      number,
      number,
      number[],
      number?,
    ][];
    return rows.map((row, id) => this.get(id));
  }
  get(id: number): HeroGuide {
    const row = this.runtime.load(8467).V6[id] as
      [string, number, number, number, number[], number?] | undefined;
    if (!row) throw new Error("武将不存在");
    return {
      id,
      name: heroName(id),
      faction: ["魏", "蜀", "吴", "群"][row[2]],
      health: row[3],
      skills: row[4].map((skill) => {
        const data = explanations[skill];
        if (!data) throw new Error(`技能说明缺失：${skillName(skill)}`);
        return {
          name: skillName(skill),
          trigger: data[0],
          effect: data[1],
          example: data[2],
        };
      }),
    };
  }
}
