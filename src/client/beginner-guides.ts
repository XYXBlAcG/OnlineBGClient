function withExtra(base: BeginnerGuide, extra: BeginnerGuide): BeginnerGuide {
  return { goal: extra.goal, steps: [...base.steps, ...extra.steps] };
}

export function guideFor(
  kind: GameKind,
  config?: GuideConfig | null,
): BeginnerGuide | undefined {
  if (kind === "scmj")
    return config?.mahjong?.mode === "washizu"
      ? washizuGuide
      : config?.mahjong?.mode === "riichi"
        ? riichiGuide
        : beginnerGuides.scmj;
  const base = beginnerGuides[kind];
  if (!base) return undefined;
  if (kind === "fxq" && config?.flight?.mode === "storm")
    return withExtra(base, flightStormExtra);
  if (kind === "tq" && config?.checkers?.mode === "siege")
    return withExtra(base, checkersSiegeExtra);
  if (kind === "graphwar" && config?.graphwar?.scenario === "storm")
    return withExtra(base, graphwarStormExtra);
  if (kind === "uno" && config?.team) return withExtra(base, unoTeamExtra);
  if (kind === "expedition" && (config?.expedition?.ascension ?? 0) > 0)
    return withExtra(base, expeditionAscensionExtra);
  return base;
}

